import { test, expect } from '@playwright/test';
test.setTimeout(120000);
for (const width of [1440, 720, 390, 320]) test(`Pro screens at ${width}px`, async ({browser}, testInfo) => {
 const context=await browser.newContext({viewport:{width,height:950},baseURL:testInfo.project.use.baseURL});
 const assert=(ok,message)=>expect(ok,message).toBe(true);
 await context.route('**/*',route=>{const host=new URL(route.request().url()).hostname;return ['localhost','127.0.0.1'].includes(host)?route.continue():route.abort();});
 await context.addInitScript(()=>{
  class TestUtterance { constructor(text) { this.text=text; } }
  Object.defineProperty(window,'SpeechSynthesisUtterance',{value:TestUtterance,configurable:true});
  let timer=null,cursor=0,paused=false;
  const engine={speaking:false,getVoices:()=>[{lang:'en-US',name:'Emi'},{lang:'en-US',name:'Cameron'}],
   cancel(){clearInterval(timer);engine.speaking=false;},pause(){paused=true;},resume(){paused=false;},
   speak(u){clearInterval(timer);cursor=0;paused=false;engine.speaking=true;queueMicrotask(()=>u.onstart?.({}));const words=[...u.text.matchAll(/\S+/g)];timer=setInterval(()=>{if(paused)return;const word=words[cursor++];if(!word){clearInterval(timer);engine.speaking=false;u.onend?.({});}else u.onboundary?.({name:'word',charIndex:word.index,charLength:word[0].length});},120);}};
  Object.defineProperty(window,'speechSynthesis',{value:engine,configurable:true});
  Object.defineProperty(navigator,'clipboard',{value:{writeText:async text=>{window.__copied=text;}},configurable:true});
 });
 const page=await context.newPage(); const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await page.getByText('Select image',{exact:true}).waitFor();
 assert(await page.locator('.upload-dropzone').isVisible(),'dropzone');
 await page.locator('.go-pro').click();
 await page.getByRole('dialog',{name:'SID Pro'}).waitFor();
 assert(await page.locator('.pro-price').textContent().then(t=>t.includes('$3.99')),'price');
 const dialogBounds=await page.getByRole('dialog',{name:'SID Pro'}).boundingBox();
 assert(dialogBounds.x>=0 && dialogBounds.x+dialogBounds.width<=width+1,'upgrade fits viewport');
 assert(await page.getByRole('dialog',{name:'SID Pro'}).getByRole('button',{name:'Go Pro',exact:true}).isDisabled(),'purchase must be disabled');
 await page.getByRole('button',{name:'Close sid pro',exact:true}).click();
 await page.getByRole('dialog').waitFor({state:'detached'});
 await page.getByRole('button',{name:'Settings',exact:true}).click();
 assert(await page.getByLabel('Reading speed',{exact:true}).isDisabled(),'free speed gated');
 const backgrounds=await page.locator('.background-options button').evaluateAll(es=>es.map(e=>e.getAttribute('aria-label')));
 assert(backgrounds.join(',')==='cream background,peach background,navy background,dark background','current palette preserved');
 await page.goto('/?preview=limit');
 assert(await page.locator('.upload-dropzone').isDisabled(),'limit disables only upload');
 assert(await page.getByRole('button',{name:'Settings',exact:true}).isEnabled(),'settings remain enabled');
 await page.goto('/?preview=reader');
 await page.getByRole('button',{name:'Listen Pro',exact:true}).click();
 assert(await page.getByRole('dialog',{name:'SID Pro'}).isVisible(),'free Listen opens upgrade');
 await page.goto('/?preview=pro');
 await page.getByRole('article',{name:'Transcribed text'}).waitFor();
 assert(await page.getByRole('button',{name:'Summary'}).count()===0,'Summary removed');
 assert(await page.getByRole('article',{name:'Transcribed text'}).textContent().then(t=>t.includes('Make sure windows are closed')),'source remains intact');
 const position=await page.evaluate(()=>{const a=document.querySelector('.reader-panel').getBoundingClientRect(),c=document.querySelector('.reader-copy-button').getBoundingClientRect();return {article:a.toJSON(),copy:c.toJSON(),overflow:document.documentElement.scrollWidth-innerWidth};});
 assert(position.overflow<=1,'no overflow '+width+' '+JSON.stringify(position));
 assert(position.copy.top>=position.article.top && position.copy.right<=position.article.right && position.copy.top-position.article.top<=24 && position.article.right-position.copy.right<=24,'Copy sits in the text panel top right corner');
 await page.getByRole('button',{name:'Copy text',exact:true}).click();
 await page.getByRole('button',{name:'Copied',exact:true}).waitFor();
 assert(await page.evaluate(()=>window.__copied).then(t=>t.includes('Make sure windows are closed')),'Copy puts the full text on the clipboard');
 await page.getByRole('button',{name:'Copy text',exact:true}).waitFor({timeout:4000});
 await page.screenshot({path:testInfo.outputPath(`pro-${width}.png`),fullPage:true});
 await page.getByRole('button',{name:'Listen',exact:true}).click();
 await page.getByRole('button',{name:'Pause reading',exact:true}).waitFor();
 await page.waitForTimeout(200);
 assert(await page.locator('.reader-copy mark').count()>0,'word highlighted');
 await page.getByRole('button',{name:'Pause reading',exact:true}).click();
 assert(await page.getByRole('button',{name:'Resume reading',exact:true}).isVisible(),'pause works');
 const playerBefore=await page.locator('.listen-player').boundingBox();
 assert(playerBefore.y>=0 && playerBefore.y+playerBefore.height<=950+1,'player stays in viewport');
 await page.evaluate(()=>window.scrollTo(0,document.body.scrollHeight/2));
 const playerAfter=await page.locator('.listen-player').boundingBox();
 assert(playerAfter.y>=0 && playerAfter.y+playerAfter.height<=950+1,'player stays visible while scrolling');
 await page.getByRole('button',{name:'Resume reading',exact:true}).click();
 assert(await page.getByRole('button',{name:'Pause reading',exact:true}).isVisible(),'resume works');
 await page.getByRole('button',{name:'Settings',exact:true}).click();
 assert(await page.getByLabel('Reading speed',{exact:true}).isEnabled(),'Pro speed enabled');
 await page.getByRole('button',{name:'Cameron en-US',exact:true}).click();
 assert(await page.getByRole('button',{name:'Cameron en-US',exact:true}).getAttribute('aria-pressed')==='true','voice setting persists');
 await page.getByRole('button',{name:'Close settings',exact:true}).click();
 await page.getByRole('dialog').waitFor({state:'detached'});
 await page.getByRole('button',{name:'Close Listen',exact:true}).click();
 assert(await page.locator('.listen-player').count()===0,'player closes');
 assert(errors.length===0,'browser errors: '+errors.join(';'));
 console.log('PASS '+width+'px');await context.close();
});

